import * as esbuild from "esbuild";
import { mkdirSync, readFileSync, renameSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { prepareShader } from "@vgpu/wgsl/prepare";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = join(ROOT, "kit", "js", "modules", "hero-shade.js");
const OUTFILE = join(ROOT, "kit", "vendor", "hero-shade.js");

export async function bundleHeroShade() {
  mkdirSync(dirname(OUTFILE), { recursive: true });
  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    outfile: `${OUTFILE}.tmp`,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    logLevel: "warning",
    loader: { ".wgsl": "text", ".glsl": "text" },
    plugins: [{
      name: "prepare-hero-shaders",
      setup(build) {
        build.onLoad({ filter: /[\\/]shades[\\/].*\.wgsl$/ }, ({ path }) => ({
          contents: `export default ${JSON.stringify(prepareShader(
            `${readFileSync(join(ROOT, "kit/js/modules/shade-common.wgsl"), "utf8")}\n${readFileSync(path, "utf8")}`,
            path,
          ))};`,
          loader: "js",
        }));
      },
    }],
    conditions: ["browser", "import"],
    mainFields: ["browser", "module", "main"],
    banner: {
      js: "/* Gvaste Pages hero shade: WebGPU first, WebGL fallback. Generated by scripts/bundle-hero-shade.mjs */",
    },
  });
  renameSync(`${OUTFILE}.tmp`, OUTFILE);
}

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  await bundleHeroShade();
  console.log(`Bundled hero shade → ${OUTFILE}`);
}
