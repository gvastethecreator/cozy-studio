// Diagram and technical drawing: each preset is one drafting convention. The prompt subject is the
// thing documented; labels stay as unreadable marks. Checked against existing blueprint, patent,
// cutaway, exploded, section, isometric, wiring and knotwork presets so these add new conventions.
const AVOID = [...STYLE_AVOID, 'readable labels or numbers', 'fake data claims'];

const words = (t: string) => t.split(/\s+/).filter(Boolean).length;
const pad = (t: string, min: number, tail: string) =>
  words(t) < min ? `${t.replace(/\.$/, '')}, ${tail}` : t;

function diagram(
  aesthetic: string,
  convention: string,
  color: string,
  surface: string,
  layout: string,
  mood: string,
  key: string,
): Dna {
  return {
    aesthetic,
    subject_treatment: `Treat the prompt's subject as the thing being documented, keeping it recognizable; all labels, numbers and notes are unreadable marks: ${convention}`,
    color_and_tone: pad(color, 9, 'following the conventions of this drawing type.'),
    lighting_and_shadow:
      'No scene lighting; depth and emphasis come only from line weight, hatching and flat tone.',
    texture_and_material: pad(surface, 9, 'with the drafting tools visible in the line quality.'),
    camera_and_composition: pad(layout, 9, 'laid out as a real sheet of this drawing type.'),
    atmosphere_and_mood: pad(mood, 8, 'from careful, purposeful drafting.'),
    rendering_and_quality:
      'Precise technical drafting with consistent line weights and believable conventions.',
    key_features: key,
  };
}

