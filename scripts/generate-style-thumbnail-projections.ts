import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const rootDir = path.resolve(import.meta.dir, '..');
const stylesAssetDir = path.join(rootDir, 'assets', 'recipes', 'styles');
const thumbnailDirName = 'style-card-thumbnails';
const defaultsDirName = 'defaults';
const outputDir = path.join(rootDir, 'lib', 'styleThumbnailPacks.generated');
const aliasesPath = path.join(import.meta.dir, 'style-thumbnail-aliases.json');
const checkMode = process.argv.includes('--check');

function packIdFor(fileName: string) {
  return fileName.match(/^SP(\d{2})-/i)?.[1]
    ? `pack_${fileName.match(/^SP(\d{2})-/i)![1]}`
    : (fileName.match(/^(pack_\d{2})/i)?.[1].toLowerCase() ?? null);
}

function assetKey(fileName: string) {
  return fileName.replace(/\.[^.]+$/, '');
}

interface ThumbnailAsset {
  key: string;
  fileName: string;
  sourceDirName: string;
}

interface ThumbnailAlias {
  alias: string;
  target: string;
  sha256: string;
}

function buildPackEntries(assets: ThumbnailAsset[]) {
  return assets
    .map(
      ({ key, fileName, sourceDirName }) =>
        `    ${JSON.stringify(key)}: new URL(${JSON.stringify(`../../assets/recipes/styles/${sourceDirName}/${fileName}`)}, import.meta.url).href,`,
    )
    .join('\n');
}

function buildGroupSource(packIds: string[], filesByPack: Map<string, ThumbnailAsset[]>) {
  const packs = packIds
    .map(
      (packId) =>
        `  ${JSON.stringify(packId)}: {\n${buildPackEntries(filesByPack.get(packId) ?? [])}\n  },`,
    )
    .join('\n');
  return [
    '// Generated by scripts/generate-style-thumbnail-projections.ts.',
    '// Add/remove style card thumbnails, then run `bun run styles:thumbnails`.',
    '',
    'export const STYLE_THUMBNAIL_PACKS: Record<string, Record<string, string>> = {',
    packs,
    '};',
    '',
  ].join('\n');
}

function buildIndexSource(packGroups: string[][]) {
  const loaders = packGroups
    .flatMap((packIds, groupIndex) =>
      packIds.map(
        (packId) =>
          `  ${JSON.stringify(packId)}: () => import('./thumbnail_group_${String(groupIndex + 1).padStart(2, '0')}').then((module) => module.STYLE_THUMBNAIL_PACKS[${JSON.stringify(packId)}] ?? {}),`,
      ),
    )
    .join('\n');
  return [
    '// Generated by scripts/generate-style-thumbnail-projections.ts.',
    '// Add/remove style card thumbnails, then run `bun run styles:thumbnails`.',
    '',
    'const STYLE_THUMBNAIL_PACK_LOADERS: Record<string, () => Promise<Record<string, string>>> = {',
    loaders,
    '};',
    '',
    'export function loadGeneratedStyleThumbnailPack(packId: string) {',
    '  return STYLE_THUMBNAIL_PACK_LOADERS[packId]?.() ?? Promise.resolve({});',
    '}',
    '',
  ].join('\n');
}

const thumbnailFiles = (await readdir(path.join(stylesAssetDir, thumbnailDirName)))
  .filter((fileName) => fileName.endsWith('.webp'))
  .sort((a, b) => a.localeCompare(b));
const defaultFiles = (await readdir(path.join(stylesAssetDir, defaultsDirName)))
  .filter((fileName) => fileName.endsWith('.webp'))
  .sort((a, b) => a.localeCompare(b));
const assetsByKey = new Map<string, ThumbnailAsset>();
for (const fileName of defaultFiles) {
  const key = assetKey(fileName);
  assetsByKey.set(key, { key, fileName, sourceDirName: defaultsDirName });
}
for (const fileName of thumbnailFiles) {
  const key = assetKey(fileName);
  assetsByKey.set(key, { key, fileName, sourceDirName: thumbnailDirName });
}
const aliases = JSON.parse(await readFile(aliasesPath, 'utf8')) as ThumbnailAlias[];
for (const alias of aliases) {
  if (assetsByKey.has(alias.alias)) {
    throw new Error(`Thumbnail alias collides with a physical asset: ${alias.alias}`);
  }
  const target = assetsByKey.get(alias.target);
  if (!target) throw new Error(`Thumbnail alias target is missing: ${alias.target}`);
  const targetPath = path.join(stylesAssetDir, target.sourceDirName, target.fileName);
  const targetHash = createHash('sha256')
    .update(await readFile(targetPath))
    .digest('hex');
  if (targetHash !== alias.sha256) {
    throw new Error(`Thumbnail alias target hash changed: ${alias.target}`);
  }
  assetsByKey.set(alias.alias, { ...target, key: alias.alias });
}
const assets = [...assetsByKey.values()].sort((a, b) =>
  `${a.key}.webp`.localeCompare(`${b.key}.webp`),
);
const filesByPack = new Map<string, ThumbnailAsset[]>();
for (const asset of assets) {
  const packId = packIdFor(asset.key);
  if (!packId) throw new Error(`Cannot resolve thumbnail pack for ${asset.key}`);
  filesByPack.set(packId, [...(filesByPack.get(packId) ?? []), asset]);
}
const packIds = [...filesByPack.keys()].sort();
const packGroups = Array.from({ length: Math.ceil(packIds.length / 2) }, (_, index) =>
  packIds.slice(index * 2, index * 2 + 2),
);
const expected = new Map<string, string>([
  ['index.ts', buildIndexSource(packGroups)],
  ...packGroups.map(
    (groupPackIds, groupIndex) =>
      [
        `thumbnail_group_${String(groupIndex + 1).padStart(2, '0')}.ts`,
        buildGroupSource(groupPackIds, filesByPack),
      ] as const,
  ),
]);

if (checkMode) {
  let stale = false;
  for (const [fileName] of expected) {
    const actual = await readFile(path.join(outputDir, fileName), 'utf8').catch(() => '');
    const referencedFiles =
      fileName === 'index.ts'
        ? packGroups.flatMap((groupPackIds, groupIndex) =>
            groupPackIds.map(() => `./thumbnail_group_${String(groupIndex + 1).padStart(2, '0')}`),
          )
        : (packGroups[Number(fileName.match(/(\d{2})/)?.[1] ?? 0) - 1] ?? []).flatMap((packId) =>
            (filesByPack.get(packId) ?? []).map(
              (asset) => `${asset.sourceDirName}/${asset.fileName}`,
            ),
          );
    const referenceCount =
      fileName === 'index.ts'
        ? (actual.match(/=>\s*import\(/g) ?? []).length
        : (actual.match(/new URL\(/g) ?? []).length;
    if (
      referenceCount !== referencedFiles.length ||
      referencedFiles.some((reference) => !actual.includes(reference))
    ) {
      console.error(`[styles:thumbnails] ${fileName} is stale.`);
      stale = true;
    }
  }
  const actualFiles = await readdir(outputDir).catch(() => []);
  if (actualFiles.some((fileName) => fileName.endsWith('.ts') && !expected.has(fileName))) {
    console.error('[styles:thumbnails] generated directory contains stale modules.');
    stale = true;
  }
  if (stale) process.exit(1);
  console.log(`[styles:thumbnails] packs=${packIds.length} thumbnails=${assets.length} current`);
  process.exit(0);
}

await rm(outputDir, { recursive: true, force: true });
await mkdir(outputDir, { recursive: true });
await Promise.all(
  [...expected].map(([fileName, source]) =>
    writeFile(path.join(outputDir, fileName), source, 'utf8'),
  ),
);
const formatter = Bun.spawn(['bunx', 'vp', 'fmt', outputDir], {
  cwd: rootDir,
  stdout: 'inherit',
  stderr: 'inherit',
});
if ((await formatter.exited) !== 0) throw new Error('Could not format thumbnail projections');
console.log(`[styles:thumbnails] packs=${packIds.length} thumbnails=${assets.length} written`);
