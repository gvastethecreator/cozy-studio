// Unit-based construction: each preset names its unit, its joint (grout, lead, gap, glue) and how
// light behaves on it. Presets must not share one generic "mosaic" template.
const words = (t: string) => t.split(/\s+/).filter(Boolean).length;
const pad = (t: string, min: number, tail: string) =>
  words(t) < min ? `${t.replace(/\.$/, '')}, ${tail}` : t;

function units(
  aesthetic: string,
  unit: string,
  joint: string,
  light: string,
  color: string,
  mood: string,
  key: string,
): Dna {
  return {
    aesthetic,
    subject_treatment: `Rebuild the prompt's subject and setting entirely from discrete units so it stays recognizable at a glance — unit: ${unit}; joints: ${joint}.`,
    color_and_tone: pad(
      color,
      9,
      'with each unit holding one color so the image is built by juxtaposition.',
    ),
    lighting_and_shadow: pad(light, 9, 'as the physical behavior of this unit.'),
    texture_and_material: `${unit}, set with ${joint}, at a unit size that keeps the subject readable.`,
    camera_and_composition:
      'Keep the prompt framing; unit size and direction follow the subject contours so forms read clearly.',
    atmosphere_and_mood: pad(mood, 8, 'coming from the handcrafted construction.'),
    rendering_and_quality:
      'Crisp, consistent units and joints across the whole image, with no smeared or random fill.',
    key_features: key,
  };
}

