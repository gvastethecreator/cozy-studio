import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "src", "studio", "generated");
const OUT = join(OUT_DIR, "kit-manifest.ts");

function walk(dir, files = []) {
  if (!existsSync(dir)) return files;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}

function collect(prefix, extensions) {
  const root = join(ROOT, prefix);
  const map = {};
  for (const file of walk(root)) {
    const rel = relative(ROOT, file).replaceAll("\\", "/");
    if (extensions && !extensions.some((ext) => rel.endsWith(ext))) continue;
    map[rel] = readFileSync(file, "utf8");
  }
  return map;
}

function cascadeCss() {
  const cascade = readFileSync(join(ROOT, "src", "styles", "kit-cascade.css"), "utf8");
  const imports = [...cascade.matchAll(/@import\s+"([^"]+)"/g)].map((match) => match[1]);
  const chunks = [];
  for (const spec of imports) {
    const abs = resolve(join(ROOT, "src", "styles"), spec);
    chunks.push(readFileSync(abs, "utf8"));
  }
  const noise = readFileSync(join(ROOT, "kit", "noise.svg"));
  const data = `data:image/svg+xml,${encodeURIComponent(noise.toString("utf8"))}`;
  const font = readFileSync(join(ROOT, "kit", "fonts", "departure-mono", "DepartureMono-Regular.woff2"));
  const fontData = `data:font/woff2;base64,${font.toString("base64")}`;
  return chunks
    .join("\n")
    .replaceAll('url("noise.svg")', `url("${data}")`)
    .replaceAll(
      'url("../fonts/departure-mono/DepartureMono-Regular.woff2")',
      `url("${fontData}")`,
    );
}

function githubFixture() {
  const cached = join(ROOT, ".cache", "github");
  if (existsSync(cached)) {
    const first = readdirSync(cached).find((name) => name.endsWith(".json"));
    if (first) {
      try {
        const parsed = JSON.parse(readFileSync(join(cached, first), "utf8"));
        if (parsed?.payload?.repo) return parsed.payload;
      } catch {}
    }
  }
  return {
    repo: {
      full_name: "gvastethecreator/gh-pages-template",
      html_url: "https://github.com/gvastethecreator/gh-pages-template",
      stargazers_count: 0,
      forks_count: 0,
      subscribers_count: 0,
      open_issues_count: 0,
      private: false,
      description: "Public GitHub fixture for Studio canvas rendering.",
      language: "TypeScript",
      updated_at: "2026-01-01T00:00:00Z",
      pushed_at: "2026-01-01T00:00:00Z",
      license: { spdx_id: "MIT" },
      topics: ["landing"],
    },
    releases: [],
    commits: [],
    languages: { TypeScript: 1 },
  };
}

function collectRegistrySectionHtml() {
  const map = {};
  for (const section of Object.values(sectionRegistry.sections ?? {})) {
    if (!section.template) continue;
    const abs = join(ROOT, section.template);
    map[String(section.template).replaceAll("\\", "/")] = readFileSync(abs, "utf8");
  }
  return map;
}

const sectionRegistry = JSON.parse(
  readFileSync(join(ROOT, "kit", "section-registry.json"), "utf8"),
);
const files = {
  ...collectRegistrySectionHtml(),
  ...collect("kit/chrome", [".html"]),
  ...collect("kit/presets", [".yaml"]),
  ...collect("kit/icons/tabler", [".svg"]),
  ...collect("tests/fixtures/profile", [".json"]),
  ...collect("playground/cases/assets", [".json"]),
  ...collect("examples/gitbound/assets", [".json"]),
  ...collect("examples/catalog/assets", [".json"]),
};
const templateLibrary = {};
const templatesDir = join(ROOT, "templates");
for (const name of readdirSync(templatesDir).filter((file) => file.endsWith(".yaml")).sort()) {
  const id = name.replace(/\.yaml$/, "");
  templateLibrary[id] = parseYaml(readFileSync(join(templatesDir, name), "utf8"));
}

mkdirSync(OUT_DIR, { recursive: true });
const body = `/* Generated by scripts/build-studio-manifest.mjs. Do not edit. */
export const KIT_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
export const KIT_CSS = ${JSON.stringify(cascadeCss())};
export const GITHUB_SNAPSHOT = ${JSON.stringify(githubFixture(), null, 2)};
export const SECTION_REGISTRY = ${JSON.stringify(sectionRegistry, null, 2)} as const;
export const TEMPLATE_LIBRARY: Record<string, Record<string, unknown>> = ${JSON.stringify(templateLibrary, null, 2)};
`;
writeFileSync(OUT, body);

const dest = join(ROOT, "public", "assets");
mkdirSync(dest, { recursive: true });
const assets = join(ROOT, "assets");
if (existsSync(assets)) cpSync(assets, dest, { recursive: true });
const caseAssets = join(ROOT, "playground", "cases", "assets");
if (existsSync(caseAssets)) cpSync(caseAssets, dest, { recursive: true });

const casesPath = join(ROOT, "playground", "cases.json");
if (existsSync(casesPath) && existsSync(caseAssets)) {
  const cases = JSON.parse(readFileSync(casesPath, "utf8")).cases ?? [];
  for (const item of cases) {
    const caseDest = join(ROOT, "public", "playground", "cases", item.id, "assets");
    mkdirSync(caseDest, { recursive: true });
    cpSync(caseAssets, caseDest, { recursive: true });
  }
}

const examplesRoot = join(ROOT, "examples");
if (existsSync(examplesRoot)) {
  for (const entry of readdirSync(examplesRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const from = join(examplesRoot, entry.name, "assets");
    if (!existsSync(from)) continue;
    const to = join(ROOT, "public", "examples", entry.name, "assets");
    mkdirSync(to, { recursive: true });
    cpSync(from, to, { recursive: true });
  }
}

console.log(`Wrote ${relative(ROOT, OUT)} (${Object.keys(files).length} kit files)`);
