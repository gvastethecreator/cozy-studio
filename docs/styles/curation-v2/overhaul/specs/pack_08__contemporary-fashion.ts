import type { Create, Dna, Spec } from '../tools/apply';

// Wardrobe theme: the preset changes clothing, styling and fashion light; the wearer, pose and
// setting come from the prompt.
const AVOID = [
  'brand logo',
  'readable label text',
  'real designer or celebrity likeness',
  'generic catalog outfit',
  'bad garment fit',
];

function wear(
  aesthetic: string,
  garments: string,
  color: string,
  light: string,
  texture: string,
  camera: string,
  mood: string,
  render: string,
  key: string,
): Dna {
  const words = (t: string) => t.split(/\s+/).filter(Boolean).length;
  const pad = (t: string, min: number, tail: string) =>
    words(t) < min ? `${t.replace(/\.$/, '')}, ${tail}` : t;
  color = pad(
    color,
    9,
    'applied to garments and accessories while skin, setting and props keep their natural color.',
  );
  light = pad(light, 9, 'shaped to reveal garment cut, drape, texture and fit on the wearer.');
  texture = pad(texture, 9, 'rendered with correct weave, weight, sheen and stitching.');
  camera = pad(camera, 9, 'keeping the full outfit silhouette and fit readable at card size.');
  mood = pad(mood, 8, "carried by the wearer's posture, styling and attitude.");
  render = pad(render, 9, 'with believable fabric weight, seams and fit detail.');
  return {
    aesthetic,
    subject_treatment: `Redress the prompt's wearer in this wardrobe while keeping their identity, age, body, pose, action and setting: ${garments}`,
    color_and_tone: color,
    lighting_and_shadow: light,
    texture_and_material: texture,
    camera_and_composition: camera,
    atmosphere_and_mood: mood,
    rendering_and_quality: render,
    key_features: key,
  };
}

